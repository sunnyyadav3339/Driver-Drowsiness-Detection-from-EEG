"""Package research/src into a private Kaggle script kernel and (optionally) push it to run on a GPU.

The kernel embeds a zip of research/src, so the exact code of every run is stored in that Kaggle
kernel version and its sha256 is written to the run's env.json. No GitHub push is needed.

Usage (from the repo root):
    python research/kaggle/launch.py --slug eeg-phase0-fast --module research.src.run_phase0 \
        --args "--models icnn_batch,icnn_running,eegnet,bandpower_lr,riemann_lr" --push
    python research/kaggle/launch.py --slug eeg-phase0-fast --fetch      # download outputs when finished

Outputs are fetched into research/results/<slug>/.
"""
import argparse
import base64
import hashlib
import io
import json
import pathlib
import shlex
import subprocess
import sys
import zipfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
BUILD = ROOT / "research" / "kaggle" / "build"
RESULTS = ROOT / "research" / "results"
USER = "sunnyydv602"
DATASETS = ["sunnyydv602/eeg-dataset"]

KERNEL_TEMPLATE = '''"""Auto-generated by research/kaggle/launch.py. Do not edit; regenerate instead."""
import base64, io, os, subprocess, sys, zipfile

CODE_ZIP = "{code}"
GIT_COMMIT = "{commit}"
CODE_SHA256 = "{sha}"
MODULE = "{module}"
RUN_ARGS = {run_args!r}

work = "/kaggle/working"
zipfile.ZipFile(io.BytesIO(base64.b64decode(CODE_ZIP))).extractall(os.path.join(work, "code"))
subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", {pip!r}])
env = dict(os.environ, GIT_COMMIT=GIT_COMMIT, CODE_SOURCE="kaggle-embedded sha256=" + CODE_SHA256, PYTHONUNBUFFERED="1")
subprocess.check_call([sys.executable, "-m", MODULE, "--out", os.path.join(work, "results"), *RUN_ARGS],
                      cwd=os.path.join(work, "code"), env=env)
'''


def git_commit():
    sha = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    dirty = subprocess.run(["git", "status", "--porcelain", "research/src"], cwd=ROOT, capture_output=True, text=True).stdout.strip()
    return sha + ("+dirty(research/src)" if dirty else "")


def pack_code():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for f in ["research/__init__.py", *sorted(p.relative_to(ROOT).as_posix() for p in (ROOT / "research" / "src").glob("*.py"))]:
            z.write(ROOT / f, f)
    data = buf.getvalue()
    return base64.b64encode(data).decode(), hashlib.sha256(data).hexdigest()


def kaggle(*args):
    cmd = [sys.executable, "-m", "kaggle", *args]
    print("$", " ".join(cmd))
    return subprocess.run(cmd, check=True)


def build(a):
    code, sha = pack_code()
    folder = BUILD / a.slug
    folder.mkdir(parents=True, exist_ok=True)
    (folder / "run.py").write_text(KERNEL_TEMPLATE.format(
        code=code, commit=git_commit(), sha=sha, module=a.module, run_args=shlex.split(a.args), pip=a.pip), encoding="utf-8")
    meta = dict(id=f"{USER}/{a.slug}", title=a.slug, code_file="run.py", language="python", kernel_type="script",
                is_private=True, enable_gpu=a.accelerator != "none", enable_internet=True, dataset_sources=DATASETS,
                competition_sources=[], kernel_sources=[])
    (folder / "kernel-metadata.json").write_text(json.dumps(meta, indent=2))
    print(f"built {folder} (code sha256 {sha[:12]}, commit {git_commit()})")
    return folder


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--slug", required=True, help="kernel name, also the results folder name")
    p.add_argument("--module", default="research.src.run_phase0")
    p.add_argument("--args", default="", help="arguments passed to the module (besides --out)")
    p.add_argument("--pip", default="pyriemann", help="extra pip package installed on Kaggle")
    p.add_argument("--accelerator", default="NvidiaTeslaT4", help='"none" runs on a CPU machine (no GPU quota)')
    p.add_argument("--push", action="store_true")
    p.add_argument("--status", action="store_true")
    p.add_argument("--fetch", action="store_true")
    a = p.parse_args()

    ref = f"{USER}/{a.slug}"
    if a.push:
        kaggle("kernels", "push", "-p", str(build(a)), *([] if a.accelerator == "none" else ["--accelerator", a.accelerator]))
    elif not (a.status or a.fetch):
        build(a)
    if a.status:
        kaggle("kernels", "status", ref)
    if a.fetch:
        out = RESULTS / a.slug
        out.mkdir(parents=True, exist_ok=True)
        kaggle("kernels", "output", ref, "-p", str(out))


if __name__ == "__main__":
    main()
